def seed_2g_url(kit, managed=False):
    """Fixed 3.1.3 m68 boot inputs; never select an OS 1.x kernel by NAND age."""
    from .core import secure_write
    from .host import reject_link
    cache = Path(kit) / "saved/firmware/iPhone1,1/7E18/url"
    reject_link(cache)
    if managed or not cache.exists():
        cache.parent.mkdir(parents=True, exist_ok=True)
        secure_write(cache, (
            "https://secure-appldnld.apple.com/iPhone/061-7481.20100202.4orot/"
            "iPhone1,1_3.1.3_7E18_Restore.ipsw\n").encode())


def select_3g_identity(stage, mode, product, board, recovery):
    """WTF's generic m68 identity is not a physical board identification."""
    fields = dict(re.findall(r"^([A-Z]+):\s*(.*?)\s*$", recovery, re.MULTILINE))
    if mode == "Normal" and stage == "prepare":
        return resolve_identity(product, board, "iPhone1,2")
    if fields.get("MODE") != mode or mode not in ("WTF", "DFU", "Recovery"):
        raise ResetError("Recovery mode changed or could not be read; reconnect and retry.")
    try:
        chip = int(fields["CPID"], 16)
    except (KeyError, ValueError) as exc:
        raise ResetError("Missing or malformed recovery chip ID.") from exc
    if mode == "WTF" and stage == "prepare":
        if chip != 0x8900:
            raise ResetError("Connected WTF device is not an S5L8900 iPhone 3G target.")
        # This chooses download inputs only. The real DFU board is checked before
        # any board-specific firmware upload, after the shared WTF transition.
        return "iPhone1,2", "n82"
    if "BDID" not in fields:
        raise ResetError("Missing recovery board ID; cannot verify an iPhone 3G.")
    identity = resolve_identity(product, board, "iPhone1,2", recovery)
    if mode == "DFU" and fields.get("SRTG") != "iBoot-636.66.3x":
        raise ResetError("Expected patched S5L8900 DFU was not detected. Re-enter WTF mode and retry.")
    if stage == "upload" and mode != "DFU":
        raise ResetError("Verified patched DFU is required before uploading the 3G iBSS.")
    return identity


def select_2g_identity(stage, mode, product, board, recovery):
    """m68 selection is provisional in WTF; real DFU must identify board 00."""
    if mode == "Normal" and stage == "prepare":
        return resolve_identity(product, board, "iPhone1,1")
    fields = {}
    for key, value in re.findall(r"^([A-Z]+):[ \t]*(.*?)[ \t\r]*$", recovery, re.MULTILINE):
        if key in fields:
            raise ResetError("Ambiguous original-iPhone USB identity; no firmware was uploaded.")
        fields[key] = value
    if fields.get("MODE") != mode or mode not in ("WTF", "DFU", "Recovery"):
        raise ResetError("Original-iPhone USB mode changed or could not be read.")
    try:
        chip = int(fields["CPID"], 16)
    except (KeyError, ValueError) as exc:
        raise ResetError("Missing or malformed original-iPhone chip ID.") from exc
    if chip != 0x8900:
        raise ResetError("The connected USB chip is not the selected original iPhone.")
    if mode == "WTF" and stage == "prepare":
        return "iPhone1,1", "m68"
    identity = resolve_identity(product, board, "iPhone1,1", recovery)
    if "BDID" not in fields:
        raise ResetError("The real original-iPhone board ID is missing.")
    # ECID zero is real on this early hardware, not a substitute generated by
    # Openup. Singleton physical USB is checked by every live caller below.
    from .backend_entry import _ecid
    try:
        _ecid(fields.get("ECID"), 16, allow_zero=True)
    except (TypeError, ValueError) as exc:
        raise ResetError("The original-iPhone ECID field is missing or malformed.") from exc
    if mode == "DFU" and fields.get("SRTG") != "iBoot-636.66.3x":
        raise ResetError("Expected patched S5L8900 DFU was not detected. Re-enter WTF mode and retry.")
    if stage == "upload" and mode != "DFU":
        raise ResetError("Verified m68 patched DFU is required before uploading iBSS.")
    return identity


def read_2g_identity(stage, mode, product, board, query):
    from .physical_usb import require_single_mobile_device
    from .recovery_timing import RecoveryProbe
    deadline = time.monotonic() + 5
    require_single_mobile_device(deadline=deadline)
    if mode == "Normal" and stage == "prepare":
        return (*select_2g_identity(stage, mode, product, board, ""), mode)
    probe = RecoveryProbe(query)
    snapshot = None
    query_deadline = min(deadline, time.monotonic() + 2)
    try:
        while time.monotonic() < query_deadline:
            snapshot = probe.poll()
            if snapshot is not None:
                break
            time.sleep(min(0.025, max(0, query_deadline - time.monotonic())))
    finally:
        probe.close()
    if not snapshot or time.monotonic() >= query_deadline:
        raise ResetError("Could not read the original iPhone's current USB identity.")
    if not mode:
        match = re.search(r"^MODE:[ \t]*(\w+)[ \t\r]*$", snapshot, re.MULTILINE)
        mode = match[1] if match else ""
    identity = select_2g_identity(stage, mode, product, board, snapshot)
    require_single_mobile_device(deadline=deadline)
    if time.monotonic() >= deadline:
        raise ResetError("Original-iPhone identity verification timed out.")
    return (*identity, mode)


def wait_2g_patched(query, *, timeout=50, clock=time.monotonic, sleep=time.sleep):
    from .physical_usb import require_single_mobile_device
    from .recovery_timing import RecoveryProbe
    from .backend_entry import _progress
    probe = RecoveryProbe(query, clock=clock)
    deadline = clock() + timeout
    _progress("Waiting for the original iPhone's patched DFU mode.")
    try:
        while clock() < deadline:
            snapshot = probe.poll()
            if snapshot:
                match = re.search(r"^MODE:[ \t]*(\w+)[ \t\r]*$", snapshot, re.MULTILINE)
                mode = match[1] if match else ""
                if mode in ("WTF", "DFU"):
                    identity = select_2g_identity("prepare", mode, "", "", snapshot)
                    if mode == "DFU":
                        require_single_mobile_device(deadline=deadline)
                        if clock() < deadline:
                            return (*identity, mode)
            sleep(min(0.025, max(0, deadline - clock())))
        raise ResetError("The original iPhone did not enter verified patched DFU in time. No iBSS was uploaded.")
    finally:
        probe.close()


HOOK = r'''
bl_ios_legacy_identity() {
    local recovery resolved product="$device_type" board="$device_model"
    if [[ $device_mode == "Normal" && $1 == "prepare" ]]; then
        # The shared entry helper already read and verified this selected serial.
        product="$device_type"
        board="$device_model"
    else
        recovery="$($irecovery -q 2>/dev/null)" ||
            error "Could not read device identity; no board-specific firmware was uploaded."
    fi
    resolved="$("$BL_IOS_PYTHON" -m ios_timeout.legacy_kit identity \
        "$1" "$device_mode" "$product" "$board" "$recovery")" ||
        error "iPhone 3G identity verification failed; firmware upload cancelled."
    IFS=$'\t' read -r device_type device_model <<< "$resolved"
    if [[ $device_mode == "WTF" ]]; then
        log "WTF identity is generic. Preparing selected iPhone1,2 / n82ap; real DFU identity will be checked before iBSS."
    else
        log "Verified iPhone 3G target: $device_type / ${device_model}ap ($device_mode)."
    fi
}

bl_ios_legacy_diagnostics() {
    local recovery
    recovery="$($irecovery -q 2>/dev/null)"
    if [[ -z $recovery ]]; then
        warn "USB diagnostic: irecovery cannot currently read the phone."
    else
        print "* Last USB state (read only):"
        printf '%s\n' "$recovery" | grep -E '^(MODE|CPID|BDID|PRODUCT|MODEL|SRTG):'
    fi
}
'''


